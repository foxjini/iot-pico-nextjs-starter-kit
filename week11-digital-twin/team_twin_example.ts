/** 캐릭터 색. 다섯 가지 중에서 고릅니다. */
export type CharacterColor = "pink" | "mint" | "sky" | "amber" | "robot";

/** 방 종류. 바닥 색과 이름이 바뀝니다. */
export type RoomKind = "farm" | "home" | "factory" | "park";

export type Desk = {
  /** ★ 가장 중요합니다 — Pico 가 주고받는 **JSON 키 그대로**.
   *  화면의 SENSORS key 와 글자 하나까지 같아야 합니다.
   *  여기가 틀리면 그 캐릭터는 **영원히 「데이터 없음」** 입니다. */
  key: string;

  /** 센서인가 액추에이터인가. 센서는 값을 받기만 하고, 액추에이터는 명령을 보냅니다. */
  kind: "sensor" | "actuator";

  /** 관람객에게 보여줄 이름 */
  label: string;

  /** 자리 번호 1~6. 1·2·3 이 뒷줄, 4·5·6 이 앞줄입니다. */
  seat: 1 | 2 | 3 | 4 | 5 | 6;

  /** 캐릭터 색 */
  character: CharacterColor;

  /** 단위 (센서만). 없으면 안 적어도 됩니다 */
  unit?: string;

  /** 막대 그래프의 최댓값 (센서만). 안 적으면 100 */
  max?: number;

  /** 주의 · 위험으로 바뀌는 값 (센서만). 안 적으면 늘 「정상」입니다 */
  warn?: number;
  danger?: number;

  /** 가장 크게 보일 주인공 하나. **팀에 하나만** 적으세요 */
  hero?: boolean;

  /** ★ 물 · 열 · 움직임이 있는 장치면 "high" 를 적습니다 (액추에이터만).
   *
   *  "high" 하나가 두 가지를 켭니다.
   *    ① 평소에는 — 누르면 바로 안 보내고 **「승인하시겠습니까」 말풍선**이 뜹니다
   *    ② 전시 모드에서는 — **아예 숨깁니다** (관람객이 켜 놓고 그냥 갑니다)
   *
   *  LED · 부저처럼 되돌아오는 것은 적지 마세요 — 관람객이 해 볼 거리가 남아야 합니다.
   *  (9주차 단계 J3 에서 정한 기준과 같습니다) */
  risk?: "high";

  /** 켤 때 보낼 값. 안 적으면 255 (지금 RGB LED 와 같은 방식) */
  onValue?: number;
};

export type OfficeConfig = {
  teamName: string;
  room: RoomKind;
  desks: Desk[];
};

