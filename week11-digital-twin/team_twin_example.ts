/** 방 종류. 바닥·벽 색과 가구가 바뀝니다. */
export type RoomKind = "farm" | "home" | "factory" | "park";

/** 장치를 놓을 **이름 있는 자리**. 좌표를 손으로 쓰지 않습니다.
 *  여섯 자리가 있고, 방 종류마다 그 자리에 어울리는 받침이 놓입니다. */
export type Spot =
  | "shelf"        // 창가 선반 — 조도·온도처럼 바깥과 관계있는 센서
  | "desk"         // 책상 위 — 아무 센서나
  | "wall"         // 벽에 붙임 — 표시등·경고등
  | "ground"       // 바닥 한가운데 — 흙·물처럼 바닥에 있는 것
  | "corner"       // 구석 — 펌프·팬처럼 큰 장치
  | "ceiling";     // 천장 — 조명

export type Device = {
  /** ★ 가장 중요합니다 — Pico 가 주고받는 **JSON 키 그대로**.
   *  2D 화면의 SENSORS key 와 글자 하나까지 같아야 합니다.
   *  여기가 틀리면 그 장치는 **영원히 「데이터 없음」** 입니다. */
  key: string;

  /** 센서인가 액추에이터인가. 센서는 값을 받기만 하고, 액추에이터는 명령을 보냅니다. */
  kind: "sensor" | "actuator";

  /** 관람객에게 보여줄 이름 */
  label: string;

  /** 방 안의 어느 자리에 놓을지. **서로 겹치지 않게** 고르세요 */
  spot: Spot;

  /** 단위 (센서만). 없으면 안 적어도 됩니다 */
  unit?: string;

  /** 막대 그래프의 최댓값 (센서만). 안 적으면 100 */
  max?: number;

  /** 주의 · 위험으로 바뀌는 값 (센서만). 안 적으면 늘 「정상」입니다 */
  warn?: number;
  danger?: number;

  /** 가장 크게 보일 주인공 하나. **팀에 하나만** 적으세요 */
  hero?: boolean;

  /** ★ 물 · 열 · 움직임이 있는 장치면 "high" 를 적습니다 (액추에이터만).
   *
   *  "high" 하나가 두 가지를 켭니다.
   *    ① 평소에는 — 누르면 바로 안 보내고 **「승인하시겠습니까」 말풍선**이 뜹니다
   *    ② 전시 모드에서는 — **아예 숨깁니다** (관람객이 켜 놓고 그냥 갑니다)
   *
   *  LED · 부저처럼 되돌아오는 것은 적지 마세요 — 관람객이 해 볼 거리가 남아야 합니다.
   *  (9주차 단계 J3 에서 정한 기준과 같습니다) */
  risk?: "high";

  /** 켤 때 보낼 값. 안 적으면 255 (지금 RGB LED 와 같은 방식) */
  onValue?: number;
};

export type TwinConfig = {
  teamName: string;
  room: RoomKind;
  devices: Device[];
};

